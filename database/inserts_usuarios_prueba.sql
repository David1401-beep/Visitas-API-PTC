INSERT INTO CITA_REUNION (
    ID_EMPLEADO,
    ID_ESTUDIANTE_ENCARGADO,
    CIT_MOTIVO,
    CIT_ESTADO,
    CIT_OBSERVACIONES,
    CIT_FECHA_REUNION
)
SELECT
    (SELECT MIN(ID_EMPLEADO)
       FROM EMPLEADOS
      WHERE UPPER(EMP_CORREO) = 'DOCENTE.PRUEBA@RICALDONE.EDU.SV'),
    (SELECT MIN(EE.ID_ESTUDIANTE_ENCARGADO)
       FROM ESTUDIANTE_ENCARGADO EE
       JOIN ESTUDIANTE E
         ON E.ID_ESTUDIANTE = EE.ID_ESTUDIANTE
       JOIN ENCARGADO EN
         ON EN.ID_ENCARGADO = EE.ID_ENCARGADO
      WHERE UPPER(E.EST_CODIGO) = 'EST-PRUEBA-001'
        AND EN.ENC_TELEFONO = '7000-0001'),
    'Revisión de avance académico',
    'PENDIENTE',
    'Cita creada por el script de datos de prueba.',
    TO_DATE('2026-09-15 09:00', 'YYYY-MM-DD HH24:MI')
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1
    FROM CITA_REUNION C
    JOIN EMPLEADOS EM
      ON EM.ID_EMPLEADO = C.ID_EMPLEADO
    JOIN ESTUDIANTE_ENCARGADO EE
      ON EE.ID_ESTUDIANTE_ENCARGADO = C.ID_ESTUDIANTE_ENCARGADO
    JOIN ESTUDIANTE E
      ON E.ID_ESTUDIANTE = EE.ID_ESTUDIANTE
    WHERE UPPER(EM.EMP_CORREO) = 'DOCENTE.PRUEBA@RICALDONE.EDU.SV'
      AND UPPER(E.EST_CODIGO) = 'EST-PRUEBA-001'
      AND C.CIT_FECHA_REUNION = TO_DATE('2026-09-15 09:00', 'YYYY-MM-DD HH24:MI')
      AND UPPER(C.CIT_MOTIVO) = 'REVISIÓN DE AVANCE ACADÉMICO'
);

