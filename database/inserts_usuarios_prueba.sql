-- 1. Este archivo NO crea, elimina ni modifica tablas o columnas.
-- 2. Los ID son columnas IDENTITY; por eso se omiten en los INSERT.
-- 3. Las llaves relacionadas se recuperan con subconsultas por correo/código.
-- 4. Cada INSERT usa NOT EXISTS para que el script pueda ejecutarse de nuevo
--    sin duplicar los datos de prueba.
-- 5. Las contraseñas están en texto plano únicamente porque la API actual las
--    compara de esa forma. Deben reemplazarse por hashes al implementar la API
--    de autenticación con BCrypt.
-- ============================================================================

