PROMPT === 6. Verificación de los datos creados ===

SELECT
    U.ID_USUARIO,
    U.USU_EMAIL,
    U.USU_ROL
FROM USUARIOS U
WHERE UPPER(U.USU_EMAIL) IN (
    'ADMIN.PRUEBA@RICALDONE.EDU.SV',
    'DOCENTE.PRUEBA@RICALDONE.EDU.SV',
    'ESTUDIANTE.PRUEBA@RICALDONE.EDU.SV'
)
ORDER BY U.ID_USUARIO;

SELECT
    E.EST_CODIGO,
    E.EST_NOMBRE || ' ' || E.EST_APELLIDO AS ESTUDIANTE,
    U.USU_EMAIL AS CORREO_DE_ACCESO,
    EN.ENC_NOMBRE || ' ' || EN.ENC_APELLIDO AS ENCARGADO,
    EE.ID_ESTUDIANTE_ENCARGADO
FROM ESTUDIANTE E
JOIN USUARIOS U
  ON U.ID_USUARIO = E.USUARIO_ESTUDIANTE
JOIN ESTUDIANTE_ENCARGADO EE
  ON EE.ID_ESTUDIANTE = E.ID_ESTUDIANTE
JOIN ENCARGADO EN
  ON EN.ID_ENCARGADO = EE.ID_ENCARGADO
WHERE UPPER(E.EST_CODIGO) = 'EST-PRUEBA-001';

SELECT
    C.ID_CITA,
    EM.EMP_NOMBRE || ' ' || EM.EMP_APELLIDO AS DOCENTE,
    E.EST_NOMBRE || ' ' || E.EST_APELLIDO AS ESTUDIANTE,
    C.CIT_MOTIVO,
    C.CIT_ESTADO,
    TO_CHAR(C.CIT_FECHA_REUNION, 'YYYY-MM-DD HH24:MI') AS FECHA_HORA
FROM CITA_REUNION C
JOIN EMPLEADOS EM
  ON EM.ID_EMPLEADO = C.ID_EMPLEADO
JOIN ESTUDIANTE_ENCARGADO EE
  ON EE.ID_ESTUDIANTE_ENCARGADO = C.ID_ESTUDIANTE_ENCARGADO
JOIN ESTUDIANTE E
  ON E.ID_ESTUDIANTE = EE.ID_ESTUDIANTE
WHERE UPPER(E.EST_CODIGO) = 'EST-PRUEBA-001'
ORDER BY C.ID_CITA;

